#!/usr/bin/env python3
"""Zeichnet das App-Symbol als Pixelbild und schreibt es in allen Grössen in den Zielordner."""
import struct
import sys
import zlib
from pathlib import Path

ART = """
................................
................................
..............G..G..............
.............GGGGGG.............
...........G.GGGGGG.G...........
...........GGGGGGGGGG...........
.............GGGGGG.............
..........dGGGGGGGGGGd..........
.........YYYYYYYYYYYYYY.........
........YYdYYYYdYYYYdYYY........
.......YYYYYdYYYYdYYYYdYY.......
.......YdYYYYdYYYYdYYYYdY.......
.......YYdYYYYdYYYYdYYYYY.......
.......YYYdYYYYdYYYYdYYYY.......
.......YYYYdYYYYdYYYYdYYY.......
.......YdYYYdYYYYdYYYYdYY.......
.......YYdYYYdYYYYdYYYYdY.......
.......YYYdYYYdYYYYdYYYYY.......
.......YYYYdYYYdYYYYdYYYY.......
.......oYYYYdYYYdYYYYdYYo.......
.......ooYYYYdYYYdYYYYYoo.......
........ooYYYYdYYYdYYYoo........
.........ooooYYYYYYoooo.........
...........oooooooooo...........
................................
................................
"""
COLORS = {'.': (15, 42, 60), 'G': (55, 160, 100), 'Y': (248, 211, 74), 'd': (201, 154, 30), 'o': (214, 160, 40)}

rows = [row.ljust(32, '.') for row in ART.strip('\n').split('\n')]
rows = ['.' * 32] * ((32 - len(rows)) // 2) + rows
rows += ['.' * 32] * (32 - len(rows))


def png(size):
    scale = size // 32
    raw = bytearray()
    for row in rows:
        line = bytearray(b'\0')
        for cell in row:
            line += bytes(COLORS[cell]) * scale
        raw += bytes(line) * scale
    def chunk(tag, data):
        body = tag + data
        return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body))
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 2, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(bytes(raw), 9)) + chunk(b'IEND', b'')


target = Path(sys.argv[1])
target.mkdir(parents=True, exist_ok=True)
for base in (32, 64, 128, 256, 512):
    (target / f'icon_{base}x{base}.png').write_bytes(png(base))
    (target / f'icon_{base // 2}x{base // 2}@2x.png').write_bytes(png(base))
(target / 'icon_512x512@2x.png').write_bytes(png(1024))
